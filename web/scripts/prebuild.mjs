// Copies the code shared with the Node server into the DesignRoom actor (Base44 deploys only the
// files inside an actor's folder) and the functions (base44/shared), and the blank-design
// template into the site; checks that the Java side (scripts/build-web-jars.sh) has been built,
// names our jar after its contents, and indexes OpenRocket's examples in OpenRocket's.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { centralEntries, zipDirectory } from '../src/lib/zip.js';

const web = join(import.meta.dirname, '..');
const server = join(web, '..', 'server');
const lib = join(web, 'base44', 'actors', 'DesignRoom', 'lib');
mkdirSync(lib, { recursive: true });
for (const f of ['model.js', 'edits.js', 'xml.js', 'history.js', 'preview.js']) {
  const banner = `// Generated by web/scripts/prebuild.mjs from server/src/${f}; edit that file instead.\n`;
  writeFileSync(join(lib, f), banner + readFileSync(join(server, 'src', f), 'utf8'));
}
// The edit history's bookkeeping and the design previews' check are shared with the pages too.
for (const f of ['history.js', 'preview.js']) {
  writeFileSync(join(web, 'src', 'lib', f),
    `// Generated by web/scripts/prebuild.mjs from server/src/${f}; edit that file instead.\n` + readFileSync(join(server, 'src', f), 'utf8'));
}
// The forecast code (functions/gfsWinds) into the Forecasts actor, which shares it for the site.
const forecasts = join(web, 'base44', 'actors', 'Forecasts', 'lib');
mkdirSync(forecasts, { recursive: true });
for (const f of ['gfs.js', 'grib2.js', 'nomads.js', 'forecaster.js']) {
  writeFileSync(join(forecasts, f), `// Generated by web/scripts/prebuild.mjs from base44/functions/gfsWinds/${f}; edit that file instead.\n`
    + readFileSync(join(web, 'base44', 'functions', 'gfsWinds', f), 'utf8'));
}
// The designs function checks drawings as the room did (server/src/preview.js).
writeFileSync(join(web, 'base44', 'shared', 'preview.js'),
  `// Generated by web/scripts/prebuild.mjs from server/src/preview.js; edit that file instead.\n` + readFileSync(join(server, 'src', 'preview.js'), 'utf8'));
mkdirSync(join(web, 'public', 'templates'), { recursive: true });
copyFileSync(join(server, 'templates', 'new-rocket.ork'), join(web, 'public', 'templates', 'new-rocket.ork'));
for (const f of ['OpenRocket-web.jar', 'orcloud-web.jar', 'preload.json']) {
  if (!existsSync(join(web, 'public', 'or', f))) {
    console.error(`Missing web/public/or/${f}: run scripts/build-web-jars.sh first.`);
    process.exit(1);
  }
}
// Our jar (orcloud-web.jar, which changes with most releases) also under a name of its own for each
// build, which the pages load: the site lets browsers keep its files for an hour, and a cached older
// copy would run against this build's pages, or mix with it, for that long after a release.
const or = join(web, 'public', 'or');
const ours = readFileSync(join(or, 'orcloud-web.jar'));
const tag = createHash('sha256').update(ours).digest('hex').slice(0, 12);
for (const f of readdirSync(or)) if (/^orcloud-web-[0-9a-f]+\.jar$/.test(f)) unlinkSync(join(or, f));
writeFileSync(join(or, `orcloud-web-${tag}.jar`), ours);
// OpenRocket's jar (42 MB, changing only with OpenRocket) is loaded with its contents' hash in
// the address, so the service worker (public/sw.js) keeps it in browsers as that version, and a new
// version is a new address for the CDN too.
const orJar = readFileSync(join(or, 'OpenRocket-web.jar'));
const openrocket = createHash('sha256').update(orJar).digest('hex').slice(0, 12);
// The parts of it OpenRocket reads as it starts, which the design page downloads in parallel as it
// opens (public/sw.js): the files it starts with, which scripts/slim-openrocket-jar.py puts first
// (scripts/openrocket-startup.txt), and the jar's directory, at its end, which is read before anything.
const orDir = zipDirectory(orJar);
const startupNames = new Set(readFileSync(join(web, '..', 'scripts', 'openrocket-startup.txt'), 'utf8')
  .split('\n').filter((l) => l.trim() && !l.startsWith('#')));
const rest = centralEntries(orJar.subarray(orDir.offset, orDir.offset + orDir.size), orDir.count)
  .filter((e) => !startupNames.has(e.name)).map((e) => e.local);
const startupEnd = rest.length ? Math.min(...rest) : orDir.offset;
writeFileSync(join(web, 'src', 'lib', 'jars.js'), `// Generated by web/scripts/prebuild.mjs: the jars OpenRocket runs from, by version (CheerpJ's /app/ is the site).
export const OPENROCKET_JAR = '/or/OpenRocket-web.jar?v=${openrocket}';
export const CLASSPATH = '/app/or/orcloud-web-${tag}.jar:/app' + OPENROCKET_JAR;
// Byte ranges of it that OpenRocket reads as it starts: its directory, and the files it starts with.
export const OPENROCKET_STARTUP = [[${orDir.offset}, ${orJar.length - 1}], [0, ${startupEnd - 1}]];
`);

// Where OpenRocket's example designs sit in its jar, so the dashboard's "From an example" reads
// just the one chosen instead of the jar's whole directory (2 MB).
const jar = orJar;
const dir = orDir;
const examples = centralEntries(jar.subarray(dir.offset, dir.offset + dir.size), dir.count)
  .filter((e) => e.name.startsWith('datafiles/examples/') && e.name.endsWith('.ork'));
writeFileSync(join(web, 'public', 'or', 'examples.json'), JSON.stringify(examples));
console.log('prebuild: shared code and templates copied');
