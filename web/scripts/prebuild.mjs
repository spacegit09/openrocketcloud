// Copies the code shared with the Node server into the DesignRoom actor (Base44 deploys only the
// files inside an actor's folder) and the blank-design template into the site, checks that the
// Java side (scripts/build-web-jars.sh) has been built, names our jar after its contents, and
// indexes OpenRocket's examples in OpenRocket's.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { centralEntries, zipDirectory } from '../src/lib/zip.js';

const web = join(import.meta.dirname, '..');
const server = join(web, '..', 'server');
const lib = join(web, 'base44', 'actors', 'DesignRoom', 'lib');
mkdirSync(lib, { recursive: true });
for (const f of ['model.js', 'edits.js', 'xml.js', 'history.js', 'preview.js']) {
  const banner = `// Generated by web/scripts/prebuild.mjs from server/src/${f}; edit that file instead.\n`;
  writeFileSync(join(lib, f), banner + readFileSync(join(server, 'src', f), 'utf8'));
}
// The edit history's bookkeeping and the design previews' check are shared with the pages too.
for (const f of ['history.js', 'preview.js']) {
  writeFileSync(join(web, 'src', 'lib', f),
    `// Generated by web/scripts/prebuild.mjs from server/src/${f}; edit that file instead.\n` + readFileSync(join(server, 'src', f), 'utf8'));
}
mkdirSync(join(web, 'public', 'templates'), { recursive: true });
copyFileSync(join(server, 'templates', 'new-rocket.ork'), join(web, 'public', 'templates', 'new-rocket.ork'));
for (const f of ['OpenRocket-web.jar', 'orcloud-web.jar', 'preload.json']) {
  if (!existsSync(join(web, 'public', 'or', f))) {
    console.error(`Missing web/public/or/${f}: run scripts/build-web-jars.sh first.`);
    process.exit(1);
  }
}
// Our jar (orcloud-web.jar, which changes with most releases) also under a name of its own for each
// build, which the pages load: the site lets browsers keep its files for an hour, and a cached older
// copy would run against this build's pages, or mix with it, for that long after a release.
const or = join(web, 'public', 'or');
const ours = readFileSync(join(or, 'orcloud-web.jar'));
const tag = createHash('sha256').update(ours).digest('hex').slice(0, 12);
for (const f of readdirSync(or)) if (/^orcloud-web-[0-9a-f]+\.jar$/.test(f)) unlinkSync(join(or, f));
writeFileSync(join(or, `orcloud-web-${tag}.jar`), ours);
writeFileSync(join(web, 'src', 'lib', 'jars.js'), `// Generated by web/scripts/prebuild.mjs; the jars OpenRocket runs from (CheerpJ's /app/ is the site).
export const CLASSPATH = '/app/or/orcloud-web-${tag}.jar:/app/or/OpenRocket-web.jar';
`);

// Where OpenRocket's example designs sit in its jar, so the dashboard's "From an example" reads
// just the one chosen instead of the jar's whole directory (2 MB).
const jar = readFileSync(join(web, 'public', 'or', 'OpenRocket-web.jar'));
const dir = zipDirectory(jar);
const examples = centralEntries(jar.subarray(dir.offset, dir.offset + dir.size), dir.count)
  .filter((e) => e.name.startsWith('datafiles/examples/') && e.name.endsWith('.ork'));
writeFileSync(join(web, 'public', 'or', 'examples.json'), JSON.stringify(examples));
console.log('prebuild: shared code and templates copied');
